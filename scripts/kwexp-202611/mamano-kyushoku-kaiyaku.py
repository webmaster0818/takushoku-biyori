def back_bdays(d, n):
    """曜日 d（0=月）から n 営業日（土日休み）さかのぼった曜日と暦日数"""
    days = 0
    cur = d
    while n > 0:
        cur = (cur - 1) % 7
        days += 1
        if cur < 5:
            n -= 1
    return cur, days



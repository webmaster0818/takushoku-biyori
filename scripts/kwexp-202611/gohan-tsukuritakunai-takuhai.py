def fmt(d):
    return f"{d.month}/{d.day}（{WD[d.weekday()]}）"


def next_weekday(d, wd, include_today=False):
    """d 以降で曜日 wd（月=0）の最初の日"""
    k = (wd - d.weekday()) % 7
    if k == 0 and not include_today:
        k = 7
    return d + dt.timedelta(days=k)



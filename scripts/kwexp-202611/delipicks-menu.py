from kwexp_util import table, src, p, h2, h3, a, ul

CHK = "2026年11月14日"
TSV = Path(__file__).resolve().parent / "delipicks-menu-20261114.tsv"
R = list(csv.DictReader(TSV.open(encoding="utf-8"), delimiter="\t"))
N = len(R)
F = lambda x, k: float(x[k])  # noqa: E731
GROUPS = ["豚肉料理", "魚介料理", "鶏肉料理", "牛肉料理", "ハンバーグ", "カレー", "パスタ・ご飯もの", "グラタン", "その他(分類外)"]
NATS = ["洋食", "和食", "中華・韓国料理", "フレンチ", "エスニック"]
PRO = [F(x, "たんぱく質g") for x in R]
P20 = sum(1 for v in PRO if v >= 20)
SALT = [F(x, "食塩相当量g") for x in R]


def fmt(v):
    return f"{v:g}"


def med(xs):
    return fmt(round(st.median(xs), 1))


group_rows = []
for g in GROUPS:
    q = [x for x in R if x["群"] == g]
    group_rows.append([
        g.replace("(分類外)", "（公式の分類外）"), f"{len(q)}品",
        f"{med([F(x, 'たんぱく質g') for x in q])}g", f"{med([F(x, 'kcal') for x in q])}kcal", f"{med([F(x, '食塩相当量g') for x in q])}g",
    ])
nat_rows = [[n, f"{sum(1 for x in R if x['国籍'] == n)}品"] for n in NATS]
bins = [(0, 10, "10g未満"), (10, 15, "10〜15g未満"), (15, 20, "15〜20g未満"), (20, 25, "20〜25g未満"), (25, 30, "25〜30g未満"), (30, 999, "30g以上")]
pro_rows = [[lab, f"{sum(1 for v in PRO if lo <= v < hi)}品"] for lo, hi, lab in bins]
STD = [x for x in R if x["単価税抜"] == "920"]
top_pro = sorted(STD, key=lambda x: -F(x, "たんぱく質g"))[:8]
top_pro_rows = [[x["メニュー名"], f"{fmt(F(x, 'たんぱく質g'))}g", f"{fmt(F(x, 'kcal'))}kcal", f"{fmt(F(x, '食塩相当量g'))}g"] for x in top_pro]
low_salt = sorted([x for x in STD if F(x, "食塩相当量g") <= 1.5], key=lambda x: (F(x, "食塩相当量g"), -F(x, "たんぱく質g")))
low_salt_rows = [[x["メニュー名"], f"{fmt(F(x, '食塩相当量g'))}g", f"{fmt(F(x, 'たんぱく質g'))}g", f"{fmt(F(x, 'kcal'))}kcal"] for x in low_salt]

list_jsx = []
for g in GROUPS:
    q = sorted([x for x in R if x["群"] == g], key=lambda x: (NATS.index(x["国籍"]), x["メニュー名"]))
    label = g.replace("(分類外)", "（公式の分類外）")
    list_jsx.append(h3(f"{label}（{len(q)}品）"))
